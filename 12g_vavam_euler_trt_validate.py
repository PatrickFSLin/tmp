def load_inputs():

    print()
    print("=" * 80)
    print("Loading reference input")
    print("=" * 80)

    data = np.load(
        INPUT_PATH
    )

    visual_tokens = np.ascontiguousarray(
        data["visual_tokens"]
        .astype(np.int64)
    )

    high_level_command = np.ascontiguousarray(
        data["high_level_command"][
            :,
            :1,
        ].astype(np.int64)
    )

    # 12f reference contains:
    #
    # (1, 1, 6, 2)
    #
    # We use the first action state as Euler initial action.

    if "initial_action" in data:

        initial_action = np.ascontiguousarray(
            data["initial_action"][
                ...,
            ].astype(np.float32)
        )

    elif "noisy_actions" in data:

        initial_action = np.ascontiguousarray(
            data["noisy_actions"][
                :,
                :1,
                ...,
            ].astype(np.float32)
        )

    else:

        raise RuntimeError(
            "joint_reference.npz does not contain "
            "initial_action or noisy_actions"
        )

    if initial_action.shape == (
        1,
        8,
        6,
        2,
    ):

        initial_action = (
            initial_action[
                :,
                :1,
                ...,
            ]
        )

    print()
    print(
        f"  visual_tokens      : "
        f"{visual_tokens.shape} "
        f"{visual_tokens.dtype}"
    )

    print(
        f"  high_level_command : "
        f"{high_level_command.shape} "
        f"{high_level_command.dtype}"
    )

    print(
        f"  initial_action     : "
        f"{initial_action.shape} "
        f"{initial_action.dtype}"
    )

    return (
        visual_tokens,
        high_level_command,
        initial_action,
    )


# ============================================================================
# TensorRT engine
# ============================================================================

def load_engine():

    print()
    print("=" * 80)
    print("Loading TensorRT engine")
    print("=" * 80)

    logger = trt.Logger(
        trt.Logger.WARNING
    )

    runtime = trt.Runtime(
        logger
    )

    with open(
        ENGINE_PATH,
        "rb",
    ) as f:

        engine_data = f.read()

    engine = (
        runtime.deserialize_cuda_engine(
            engine_data
        )
    )

    if engine is None:

        raise RuntimeError(
            "Failed to deserialize TensorRT engine."
        )

    print()
    print(
        "[OK] TensorRT engine deserialized"
    )

    return (
        runtime,
        engine,
    )


def inspect_engine(engine):

    print()
    print(
        "[TRT] Engine I/O"
    )

    for i in range(
        engine.num_io_tensors
    ):

        name = (
            engine.get_tensor_name(i)
        )

        mode = (
            engine.get_tensor_mode(name)
        )

        dtype = (
            engine.get_tensor_dtype(name)
        )

        shape = tuple(
            engine.get_tensor_shape(name)
        )

        print()
        print(
            f"  {name}"
        )

        print(
            f"    mode  : {mode}"
        )

        print(
            f"    dtype : {dtype}"
        )

        print(
            f"    shape : {shape}"
        )


# ============================================================================
# One TensorRT inference step
# ============================================================================

def run_trt_step(
    engine,
    context,
    stream,
    allocations,
    host_outputs,
    visual_tokens,
    noisy_actions,
    high_level_command,
    diffusion_step,
):

    input_map = {

        "visual_tokens":
            visual_tokens,

        "noisy_actions":
            noisy_actions,

        "high_level_command":
            high_level_command,

        "diffusion_step":
            diffusion_step,
    }

    # ------------------------------------------------------------
    # H -> D
    # ------------------------------------------------------------

    for name, array in input_map.items():

        cuda_memcpy_htod(
            allocations[name],
            array,
        )

    # ------------------------------------------------------------
    # Set tensor addresses
    # ------------------------------------------------------------

    for name, ptr in allocations.items():

        ok = context.set_tensor_address(
            name,
            int(ptr),
        )

        if not ok:

            raise RuntimeError(
                f"Failed to set tensor address: "
                f"{name}"
            )

    # ------------------------------------------------------------
    # Execute
    # ------------------------------------------------------------

    ok = context.execute_async_v3(
        stream_handle=int(stream)
    )

    if not ok:

        raise RuntimeError(
            "TensorRT execute_async_v3 failed."
        )

    cuda_stream_sync(
        stream
    )

    # ------------------------------------------------------------
    # D -> H
    # ------------------------------------------------------------

    output = host_outputs[
        "action_velocity"
    ]

    cuda_memcpy_dtoh(
        output,
        allocations[
            "action_velocity"
        ],
    )

    return output.copy()


# ============================================================================
# Allocate TensorRT buffers
# ============================================================================

def allocate_buffers(engine):

    allocations = {}
    host_outputs = {}

    print()
    print(
        "[TRT] Allocating buffers..."
    )

    for i in range(
        engine.num_io_tensors
    ):

        name = (
            engine.get_tensor_name(i)
        )

        mode = (
            engine.get_tensor_mode(name)
        )

        dtype = (
            engine.get_tensor_dtype(name)
        )

        shape = tuple(
            engine.get_tensor_shape(name)
        )

        if any(
            d < 0
            for d in shape
        ):

            raise RuntimeError(
                f"Dynamic shape not supported: "
                f"{name} {shape}"
            )

        np_dtype = np.dtype(
            trt.nptype(dtype)
        )

        nbytes = (
            int(
                np.prod(shape)
            )
            * np_dtype.itemsize
        )

        allocations[name] = (
            cuda_malloc(nbytes)
        )

        if mode == trt.TensorIOMode.OUTPUT:

            host_outputs[name] = np.empty(
                shape,
                dtype=np_dtype,
            )

        print(
            f"  {name}: "
            f"dtype={np_dtype} "
            f"shape={shape} "
            f"nbytes={nbytes}"
        )

    return (
        allocations,
        host_outputs,
    )


# ============================================================================
# Euler integration
# ============================================================================

def run_euler(
    engine,
    visual_tokens,
    high_level_command,
    initial_action,
):

    print()
    print("=" * 80)
    print("Thor TensorRT + Euler Integration")
    print("=" * 80)

    context = (
        engine.create_execution_context()
    )

    if context is None:

        raise RuntimeError(
            "Failed to create execution context."
        )

    (
        allocations,
        host_outputs,
    ) = allocate_buffers(
        engine
    )

    stream = None

    velocity_history = []

    action_history = []

    # ------------------------------------------------------------
    # Current action
    # ------------------------------------------------------------

    action = np.ascontiguousarray(
        initial_action.copy()
        .astype(np.float32)
    )

    # Ensure inference shape
    if action.shape != (
        1,
        1,
        6,
        2,
    ):

        raise RuntimeError(
            "Unexpected initial action shape: "
            f"{action.shape}"
        )

    t = np.float32(
        0.0
    )

    action_history.append(
        action.copy()
    )

    print()
    print(
        f"  num_inference_steps : "
        f"{NUM_INFERENCE_STEPS}"
    )

    print(
        f"  delta_t             : "
        f"{DELTA_T}"
    )

    try:

        stream = cuda_stream_create()

        print()
        print(
            "[OK] CUDA stream created"
        )

        for step in range(
            NUM_INFERENCE_STEPS
        ):

            print()
            print(
                "-" * 80
            )

            print(
                f"Euler Step "
                f"{step + 1}/"
                f"{NUM_INFERENCE_STEPS}"
            )

            print(
                f"  t = {t:.6f}"
            )

            diffusion_step = np.ascontiguousarray(
                np.array(
                    [[t]],
                    dtype=np.float32,
                )
            )

            velocity = run_trt_step(
                engine,
                context,
                stream,
                allocations,
                host_outputs,
                visual_tokens,
                action,
                high_level_command,
                diffusion_step,
            )

            velocity_history.append(
                velocity.copy()
            )

            print()
            print(
                "[Velocity]"
            )

            print(
                f"  min   : "
                f"{velocity.min()}"
            )

            print(
                f"  max   : "
                f"{velocity.max()}"
            )

            print(
                f"  mean  : "
                f"{velocity.mean()}"
            )

            # ----------------------------------------------------
            # Euler update
            # ----------------------------------------------------

            action = np.ascontiguousarray(
                action
                + DELTA_T * velocity
            )

            action_history.append(
                action.copy()
            )

            print()
            print(
                "[Action after Euler update]"
            )

            print(
                f"  min   : "
                f"{action.min()}"
            )

            print(
                f"  max   : "
                f"{action.max()}"
            )

            print(
                f"  mean  : "
                f"{action.mean()}"
            )

            t = np.float32(
                t + DELTA_T
            )

    finally:

        if stream is not None:

            cuda_stream_sync(
                stream
            )

        for ptr in allocations.values():

            cuda_free(ptr)

        if stream is not None:

            cuda_stream_destroy(
                stream
            )

    velocity_history = np.stack(
        velocity_history,
        axis=0,
    )

    action_history = np.stack(
        action_history,
        axis=0,
    )

    final_trajectory = action.copy()

    return (
        velocity_history,
        action_history,
        final_trajectory,
    )


