def cuda_check(result, name):

    if isinstance(result, tuple):
        err = result[0]
    else:
        err = result

    if err != driver.CUresult.CUDA_SUCCESS:
        raise RuntimeError(
            f"{name} failed: {err}"
        )

    return result


def cuda_malloc(nbytes):

    result = driver.cuMemAlloc(
        int(nbytes)
    )

    cuda_check(
        result,
        "cuMemAlloc"
    )

    return result[1]


def cuda_free(ptr):

    if ptr is None:
        return

    result = driver.cuMemFree(
        ptr
    )

    cuda_check(
        result,
        "cuMemFree"
    )


def cuda_memcpy_htod(
    ptr,
    host_array,
):

    arr = np.ascontiguousarray(
        host_array
    )

    result = driver.cuMemcpyHtoD(
        int(ptr),
        arr,
        int(arr.nbytes),
    )

    cuda_check(
        result,
        "cuMemcpyHtoD"
    )


def cuda_memcpy_dtoh(
    host_array,
    ptr,
):

    arr = np.ascontiguousarray(
        host_array
    )

    result = driver.cuMemcpyDtoH(
        arr,
        int(ptr),
        int(arr.nbytes),
    )

    cuda_check(
        result,
        "cuMemcpyDtoH"
    )


def cuda_stream_create():

    result = driver.cuStreamCreate(0)

    cuda_check(
        result,
        "cuStreamCreate"
    )

    return result[1]


def cuda_stream_destroy(stream):

    if stream is None:
        return

    result = driver.cuStreamDestroy(
        stream
    )

    cuda_check(
        result,
        "cuStreamDestroy"
    )


def cuda_stream_sync(stream):

    result = driver.cuStreamSynchronize(
        stream
    )

    cuda_check(
        result,
        "cuStreamSynchronize"
    )


